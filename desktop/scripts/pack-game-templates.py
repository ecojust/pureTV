#!/usr/bin/env python3
"""Build the Manager's local APK templates from the officially signed single-game releases."""
import argparse
import hashlib
import io
import json
import struct
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def apk_parts(raw):
    # Split at ZIP boundaries without re-encoding any bytes. Deflated code, resources
    # and controller assets can then be shared across independently signed APKs.
    with zipfile.ZipFile(io.BytesIO(raw)) as apk:
        members = sorted(apk.infolist(), key=lambda member: member.header_offset)
    previous = 0
    for member in members:
        start = member.header_offset
        if raw[start:start + 4] != b'PK\x03\x04':
            raise ValueError(f'Invalid local header for {member.filename}')
        name_size, extra_size = struct.unpack_from('<HH', raw, start + 26)
        payload = start + 30 + name_size + extra_size
        end = payload + member.compress_size
        if previous > start or end > len(raw):
            raise ValueError(f'Invalid ZIP member bounds for {member.filename}')
        yield raw[previous:payload]
        yield raw[payload:end]
        previous = end
    yield raw[previous:]


def generate(signed_dir, build_tools, out_dir):
    verifier = ROOT / 'tools/hosted-games-tv/package-release.py'
    subprocess.run([sys.executable, verifier, '--signed', signed_dir, '--tools', build_tools], check=True)
    receipt = json.loads((signed_dir / 'packages.json').read_text())
    blob = bytearray()
    positions = {}
    entries = []
    for game in receipt['packages']:
        game_id = game['id']
        apk = signed_dir / game['file']
        package = game['packageName']
        raw = apk.read_bytes()
        if hashlib.sha256(raw).hexdigest() != game['sha256']:
            raise ValueError(f'Signed APK changed after verification for {game_id}')
        spans = []
        for part in apk_parts(raw):
            if not part:
                continue
            offset = positions.get(part)
            if offset is None:
                offset = len(blob)
                blob.extend(part)
                positions[part] = offset
            if spans and spans[-1][0] + spans[-1][1] == offset:
                spans[-1][1] += len(part)
            else:
                spans.append([offset, len(part)])
        if b''.join(blob[o:o+n] for o, n in spans) != raw:
            raise ValueError(f'Cannot reproduce signed bytes for {game_id}')
        spans_code = ', '.join(f'({offset}, {size})' for offset, size in spans)
        entries.append(f'    EmbeddedGame {{\n        id: "{game_id}", file_name: "{apk.name}",\n'
                       f'        package_name: "{package}", bytes: {len(raw)},\n'
                       f'        sha256: "{game["sha256"]}",\n'
                       f'        parts: &[{spans_code}],\n    }},')
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / 'parts.bin').write_bytes(blob)
    (out_dir / 'index.rs').write_text('// Generated by desktop/scripts/pack-game-templates.py\n&[\n'
                                      + '\n'.join(entries) + '\n]\n')
    print(f'{len(entries)} signed APKs share {len(blob):,} bytes of template data')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--signed-dir', type=Path, required=True)
    parser.add_argument('--build-tools', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT / 'desktop/web-game-templates')
    args = parser.parse_args()
    generate(args.signed_dir, args.build_tools, args.output)
