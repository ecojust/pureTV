// For words also used as internal IDs, the source fragments include their display context.
export function localize(path, source) {
  for (const [original, chinese] of Object.entries(labels[path] ?? {})) {
    for (const q of ["'", '"', '`']) {
      source = source.replaceAll(q + original + q, () => q + chinese + q);
    }
  }
  for (const [original, chinese] of fragments[path] ?? []) {
    source = source.replaceAll(original, () => chinese);
  }
  return source;
}
