const units = {ft: '英尺', kt: '节', fpm: '英尺/分', NM: '海里', m: '米', s: '秒'};
function translation(text) {
  if (Object.hasOwn(labels, text)) return labels[text];
  for (const [pattern, replacement] of formats) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  const measure = /^([+−±-]?[\d,.]+) (ft|kt|fpm|NM|m|s)$/.exec(text);
  if (measure) return measure[1] + ' ' + units[measure[2]];
  for (const [pattern, translated] of resultTemplates) {
    const match = pattern.exec(text);
    if (match) return translated.replace(/\{(\d+)\}/g, (_, n) => flightResultText(match[Number(n)]));
  }
  return null;
}

export function flightResultText(text) {
  if (!text || typeof text !== 'string') return text;
  const known = translation(text);
  if (known !== null) return known;
  // Several drills append independent feedback sentences to the landing result.
  for (const end of text.matchAll(/[.。] (?=[A-Z\u4e00-\u9fff])/g)) {
    const first = text.slice(0, end.index + 1);
    const translated = translation(first) ?? (/[\u4e00-\u9fff]/.test(first) ? first : null);
    if (translated !== null) return translated + flightResultText(text.slice(end.index + 2));
  }
  return text;
}
