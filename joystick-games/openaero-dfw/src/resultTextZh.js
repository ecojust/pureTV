const formats = [
  [/^(.+) not finished$/i, (_, activity) => flightResultText(activity) + '未完成'],
  [/^(.+) failed$/i, (_, activity) => flightResultText(activity) + '失败'],
  [/^Distance from the (pole|field) \(asked: ([\d,]+) ft\)$/i, (_, point, distance) => '距' + (point === 'pole' ? '标杆' : '场地') + '的距离（目标 ' + distance + ' 英尺）'],
  [/^Radius \(asked: ([\d,]+) ft\)$/i, '半径（目标 $1 英尺）'],
  [/^Time at (\d+)-(\d+) kt \(test: \+0\/-10\)$/, '保持 $1–$2 节的时间（允许偏差 +0/−10 节）'],
  [/^Time at (\d+)-(\d+) kt(, averaged through the bumps)? \(test: up to 10 kt over, never under\)$/, (_, low, high, gust) => '保持 ' + low + '–' + high + ' 节的时间' + (gust ? '（按阵风平均值计算）' : '') + '，允许超出 10 节，不能低于目标'],
  [/^Height until (\d+) kt$/, '加速到 $1 节时的高度'],
  [/^Aileron into the wind, to (\d+) kt$/, '达到 $1 节前的迎风副翼输入'],
  [/^Track over the centreline, (\d+)-(\d+) ft$/, '$1–$2 英尺之间的中线保持'],
  [/^Down to (.+)$/, '下降目标 $1'],
  [/^([±+−\d.,]+) (ft|kt|m|°) (at worst|at most|on average)$/, (_, n, unit, mode) => (mode === 'on average' ? '平均 ' : '最大 ') + n + ({ft:' 英尺', kt:' 节', m:' 米', '°':'°'})[unit]],
  [/^([\d.]+)° off( at worst)?$/, '航向偏差 $1°'],
  [/^([\d,.]+)% of normal$/, '正常值的 $1%'],
  [/^(Lost|Gained) ([\d,.]+) ft: the test allows 100\..*Capped at D\.$/, (_, direction, n) => (direction === 'Lost' ? '下降' : '上升') + '了 ' + n + ' 英尺，超过 100 英尺的允许偏差。最高 D。']
];
export function flightResultText(text) {
  if (!text || typeof text !== 'string') return text;
  if (Object.hasOwn(labels, text)) return labels[text];
  for (const [pattern, replacement] of formats) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}
